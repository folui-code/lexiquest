#!/usr/bin/env python3
"""
Extract vocabulary cards from the "Guessing Cards" PowerPoint decks in
uploads/vocabulary/*.pptx and write them to data/vocab.js for the game.

Usage:  python3 tools/extract_vocab.py
"""
import glob
import html
import json
import os
import re
import zipfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC_GLOB = os.path.join(ROOT, "uploads", "vocabulary", "*.pptx")
OUT = os.path.join(ROOT, "data", "vocab.js")


def slide_paragraphs(xml):
    paras = []
    for p in re.findall(r"<a:p>.*?</a:p>|<a:p .*?</a:p>", xml, flags=re.S):
        text = "".join(re.findall(r"<a:t>(.*?)</a:t>", p, flags=re.S))
        text = html.unescape(text).strip()
        if text:
            paras.append(text)
    return paras


def after(label, paras):
    for p in paras:
        if label in p:
            return p.split(label, 1)[1].strip(" :")
    return ""


def parse_card(paras, deck):
    header = next((p for p in paras if "WORD CARD" in p), None)
    if not header:
        return None
    topic = header.split("•", 1)[1].strip() if "•" in header else ""
    pos = next((p.replace("📌", "").strip() for p in paras if p.startswith("📌")), "")
    meaning = after("Meaning:", paras)
    syn = after("Key Clues:", paras)
    context = after("New Context:", paras).strip().strip('"“”')
    try:
        idx = next(i for i, p in enumerate(paras) if "TARGET WORD" in p)
        word = paras[idx + 1].strip()
    except (StopIteration, IndexError):
        return None
    # normalise blanks like "[ ______ ]" -> "___"
    context = re.sub(r"\[\s*_+\s*\]", "___", context)
    return {
        "word": word,
        "pos": pos.title(),
        "topic": topic.title(),
        "meaning": meaning,
        "synonyms": [s.strip() for s in syn.split(",") if s.strip()],
        "context": context,
        "deck": deck,
    }


def main():
    cards, seen = [], set()
    for path in sorted(glob.glob(SRC_GLOB)):
        deck = os.path.splitext(os.path.basename(path))[0]
        with zipfile.ZipFile(path) as z:
            names = [n for n in z.namelist() if re.match(r"ppt/slides/slide\d+\.xml$", n)]
            names.sort(key=lambda n: int(re.findall(r"\d+", n)[-1]))
            for n in names:
                card = parse_card(slide_paragraphs(z.read(n).decode("utf8")), deck)
                if card and card["word"].lower() not in seen:
                    seen.add(card["word"].lower())
                    card["id"] = len(cards)
                    cards.append(card)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf8") as f:
        f.write("// AUTO-GENERATED by tools/extract_vocab.py — do not edit by hand.\n")
        f.write("window.VOCAB = ")
        json.dump(cards, f, ensure_ascii=False, indent=2)
        f.write(";\n")
    print(f"Wrote {len(cards)} cards to {OUT}")


if __name__ == "__main__":
    main()
